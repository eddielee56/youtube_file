# -*- coding: utf-8 -*-
"""AutoRender V4.2: reviewed facts -> Gemini conversational bridges -> Azure internal preview.
Requires sibling AutoRender_V39 (approval validation) and AutoRender_V21 (renderer).
Never approves new facts, never uploads, never makes publishable output.
"""
from __future__ import annotations
import argparse, datetime as dt, getpass, hashlib, importlib.util, json, os
from pathlib import Path
import re, subprocess, sys, urllib.request, urllib.error

HERE=Path(__file__).resolve().parent
PROJECT=HERE.parent
REVIEW_MOD=PROJECT/'AutoRender_V39'/'autorender_v39.py'
RENDER_MOD=PROJECT/'AutoRender_V21'/'autorender_v21_preview.py'
OUTPUT=HERE/'output'
MODEL='gemini-3.5-flash'
BRIDGE_FIELDS=('hook','benefit_lead','eligibility_lead','deadline_lead','caveat_lead','outro')
FALLBACK={
 'hook':'有住宿計畫的朋友，這項活動值得先看清楚喔！',
 'benefit_lead':'先來看看這次的活動重點。',
 'eligibility_lead':'接著確認參加條件，這部分要注意喔。',
 'deadline_lead':'活動時間也要記得看清楚。',
 'caveat_lead':'另外有個重要提醒。',
 'outro':'你會考慮參加嗎？留言跟我分享！',
}
# Only conversational bridge fragments generated by AI; exact reviewed claims are appended by code.
NO_CLAIM=re.compile(r'[0-9０-９%％$＄€£¥￥]|百分之|截止|到期|加碼|回饋|免年費|免費|保證|[零〇一二三四五六七八九十百千萬億兩]+(?:成|倍|元|點|哩|天|月|年)')
BAD_STYLE=('超讚','好康','快來看看','絕對','千萬別錯過','穩賺','保證賺')
class StopV42(Exception):pass

def module(name,path):
    if not path.is_file():raise StopV42('Missing sibling module: '+str(path))
    sp=importlib.util.spec_from_file_location(name,path)
    mod=importlib.util.module_from_spec(sp)
    sp.loader.exec_module(mod)
    return mod

def read(path):
    x=json.loads(Path(path).read_text(encoding='utf-8-sig'))
    if not isinstance(x,dict):raise StopV42('Input must be JSON object')
    return x

def save(path,x):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(x,ensure_ascii=False,indent=2),encoding='utf-8')

def canonical_sha(data):
    return hashlib.sha256(json.dumps(data,ensure_ascii=False,sort_keys=True,separators=(',',':')).encode('utf-8')).hexdigest()

def approved(path):
    rev=module('v39_review_validator',REVIEW_MOD)
    try:return rev.validate(read(path))
    except Exception as e:raise StopV42('V3.9 approval or evidence gate failed: '+str(e)) from None

def validate_bridges(b):
    if not isinstance(b,dict) or set(b)!=set(BRIDGE_FIELDS):raise StopV42('Six bridge keys required exactly')
    for key,val in b.items():
        if not isinstance(val,str) or not 2<=len(val.strip())<=65:raise StopV42('Invalid bridge length: '+key)
        if NO_CLAIM.search(val) or re.search('https?://',val,re.I):raise StopV42('Potential factual claim in bridge: '+key)
        if '哦' in val or any(t in val for t in BAD_STYLE):raise StopV42('Style rejected: '+key)
    return {k:b[k].strip() for k in BRIDGE_FIELDS}

def prompt(facts):
    return ('你是台灣繁體中文短影音旁白編輯。只寫六個「不含優惠事實」的簡短口語連接句，'
            '不可講活動內容、福利、數字、金額、資格、日期、百分比、品牌、比較或保證；這些會由程式從人工審核資料補上。'
            '溫暖自然、活潑但不浮誇，偶爾用「喔」或「啊」，不用「哦」。'
            '不要使用「超讚」「好康」「快來看看」「絕對」「千萬別錯過」等制式廣告語。'
            '每句 6 到 35 字，六句之中最多兩句帶「喔」。'
            'hook 直接引出主題，不要誇大；outro 只邀請留言互動，不要提醒官網條款（程式會自行補上官方條款提醒）。'
            '嚴格回傳 JSON，六個欄位：'+','.join(BRIDGE_FIELDS)+'。'
            '僅提供語氣情境（不可重述其事實）：'+json.dumps({'type':facts['type'],'title':facts['title']},ensure_ascii=False))

def gemini(facts,model,key):
    if not re.fullmatch(r'gemini-[A-Za-z0-9.-]{2,75}',model):raise StopV42('Invalid model ID')
    schema={'type':'object','properties':{k:{'type':'string'} for k in BRIDGE_FIELDS},'required':list(BRIDGE_FIELDS)}
    request={'contents':[{'role':'user','parts':[{'text':prompt(facts)}]}],
             'generationConfig':{'responseMimeType':'application/json','responseJsonSchema':schema,
                                 'temperature':0.35,'maxOutputTokens':2048}}
    url=f'https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent'
    req=urllib.request.Request(url,method='POST',data=json.dumps(request,ensure_ascii=False).encode('utf-8'),
                               headers={'Content-Type':'application/json','x-goog-api-key':key})
    try:
        with urllib.request.urlopen(req,timeout=55) as resp:
            payload=json.loads(resp.read(1024*1024))
    except urllib.error.HTTPError as e:raise StopV42(f'Gemini HTTP {e.code}; check model permissions or quota') from None
    except (urllib.error.URLError,TimeoutError) as e:raise StopV42('Gemini network error or timeout') from None
    try:
        cand=payload['candidates'][0]
        reason=cand.get('finishReason','')
        if reason and reason!='STOP':raise StopV42('Gemini finishReason='+str(reason))
        raw=''.join(p.get('text','') for p in cand['content']['parts'])
        bridges=json.loads(raw)
        return validate_bridges(bridges)
    except (KeyError,IndexError,ValueError,TypeError):raise StopV42('Gemini JSON schema or content invalid') from None

def polish_bridges(b):
    # Deterministic style pass, no paraphrase of source facts.
    result={}
    for k,v in b.items():
        v=re.sub(r'([！!？?。])\1+',r'\1',v.strip())
        result[k]=v
    if sum(v.count('喔') for v in result.values())>2:
        n=0
        for k,v in result.items():
            def limit(match):
                nonlocal n
                n+=1
                return '喔' if n<=2 else ''
            result[k]=re.sub('喔',limit,v)
    return validate_bridges(result)

def compose(facts,b):
    # Immutable factual strings copied byte-for-byte; no AI paraphrase of sensitive facts.
    base=[
      {'label':'開場','heading':facts['title'],'detail':facts['program'],'narration':b['hook']},
      {'label':'優惠重點','heading':facts['headline'],'detail':facts['benefit'],
       'narration':b['benefit_lead']+facts['headline']+'。'+facts['benefit']},
      {'label':'適用資格','heading':'參加條件','detail':facts['eligibility'],
       'narration':b['eligibility_lead']+facts['eligibility']},
      {'label':'活動期限','heading':facts['deadline'],'detail':'依活動官網條款',
       'narration':b['deadline_lead']+facts['deadline']},
      {'label':'重要限制','heading':'注意事項','detail':facts['caveat'],
       'narration':b['caveat_lead']+facts['caveat']},
      {'label':'結尾','heading':'查看完整官方條款','detail':'僅供內部審核',
       'narration':b['outro']+facts['conclusion']}
    ]
    required={1:('headline','benefit'),2:('eligibility',),3:('deadline',),4:('caveat',),5:('conclusion',)}
    for i,ks in required.items():
        for k in ks:
            if facts[k] not in base[i]['narration']:raise StopV42('Locked fact missing: '+k)
    return base

def draft(input_path,model=MODEL,mode='gemini',key=None):
    inp=Path(input_path).resolve()
    facts=approved(inp)
    generator='OFFLINE_LOCAL_BRIDGES'
    if mode=='gemini':
        key=key or os.environ.get('GEMINI_API_KEY','').strip() or getpass.getpass('Gemini API key (hidden): ')
        if not key:raise StopV42('Missing Gemini API key')
        bridges=polish_bridges(gemini(facts,model,key))
        generator='GEMINI_REVIEW_REQUIRED'
    else:bridges=validate_bridges(FALLBACK)
    scenes=compose(facts,bridges)
    out=OUTPUT/facts['slug']
    snapshot_hash=canonical_sha(facts)
    storyboard={'version':'4.2','event_key':facts['event_key'],'input_path':str(inp),
                'snapshot_sha256':snapshot_hash,'generator':generator,'model':model if mode=='gemini' else None,
                'publication_approved':False,'requires_editorial_review':True,'scenes':scenes}
    save(out/'six_scene_storyboard.json',storyboard)
    save(out/'source_fact_snapshot.json',facts)
    save(out/'bridge_fragments.json',bridges)
    (out/'narration_draft.txt').write_text('\n'.join(s['narration'] for s in scenes),encoding='utf-8-sig')
    print('V4.2 DRAFT READY:',out)
    print('GENERATOR:',generator)
    print('INTERNAL REVIEW ONLY; YOUTUBE UPLOAD DISABLED')
    return out

def load_checked_draft(input_path):
    facts=approved(input_path)
    folder=OUTPUT/facts['slug']
    sb=read(folder/'six_scene_storyboard.json')
    snap=read(folder/'source_fact_snapshot.json')
    b=validate_bridges(read(folder/'bridge_fragments.json'))
    if canonical_sha(facts)!=sb['snapshot_sha256'] or canonical_sha(snap)!=sb['snapshot_sha256']:
        raise StopV42('Reviewed facts changed since draft. Regenerate and review first')
    if sb['event_key']!=facts['event_key'] or sb['publication_approved'] is not False:
        raise StopV42('Wrong event or invalid publication flag')
    scenes=compose(facts,b)
    if sb['scenes']!=scenes:raise StopV42('Storyboards were modified; stop to avoid unreviewed voice')
    return facts,scenes,folder

def render(input_path):
    facts,scenes,folder=load_checked_draft(Path(input_path).resolve())
    # Reuse V2.1 verified timestamping, card creation and FFmpeg pipeline; inject V4.2 narration.
    v21=module('v21_renderer_v42',RENDER_MOD)
    x={k:facts[k] for k in ('type','title','hook','program','headline','benefit','eligibility','deadline','caveat','conclusion',
                             'source_url','checked_at','valid_until')}
    x.update(slug='v42_'+facts['slug'],source_verified=False,approved_for_publication=False)
    mapped=[]
    tags=['01 / 開場','02 / 優惠重點','03 / 適用資格','04 / 活動期限','05 / 注意事項','06 / 結尾']
    for i,s in enumerate(scenes):
        mapped.append({'tag':tags[i],'heading':s['heading'],'detail':s['detail'],'narration':s['narration']})
    v21.scenes=lambda _:mapped
    out=v21.outdir(x,True)
    # Recheck the string actually used for voice is the one the AI generated and approved facts supplied.
    items,script=v21.prepare(x,out)
    if script!='\n'.join(s['narration'] for s in scenes):raise StopV42('Renderer narration mismatch')
    print('V4.2 USING GENERATED NARRATION:',folder/'narration_draft.txt',flush=True)
    timings=v21.voice(x,out,items,script,demo_voice=True)
    movie=v21.make_video(x,out,timings,True,demo_voice=True)
    save(folder/'render_receipt.json',{'event_key':facts['event_key'],'snapshot_sha256':canonical_sha(facts),
        'preview_only':True,'publication_approved':False,'auto_upload':False,
        'narration_sha256':hashlib.sha256(script.encode('utf8')).hexdigest(),'mp4_path':str(movie),
        'created_at':dt.datetime.now(dt.timezone.utc).isoformat()})
    print('V4.2 PREVIEW READY:',movie)
    return movie

def selftest():
    # Fully offline; copies approved sample with current dates only in memory (no claim of real verification).
    from unittest.mock import patch
    today=dt.datetime.now(dt.timezone(dt.timedelta(hours=8))).date()
    fake={'event_key':'synthetic|test','type':'hotel_to_airline','slug':'synthetic_test',
          'source_url':'https://example.org/test','checked_at':today.isoformat(),'valid_until':(today+dt.timedelta(days=10)).isoformat(),
          'source_verified':True,'approved_for_preview':True,'publication_approved':False,
          'reviewer_confirmation':'I_CHECKED_OFFICIAL_TERMS',
          'evidence':[{'field':k,'official_url':'https://example.org/test','excerpt':'FICTIONAL TEST'} for k in ('bonus_or_value','dates','eligibility')]}
    fake.update(title='虛構活動',program='純測試',hook='測試開場',headline='測試優惠內容',benefit='測試數值',eligibility='測試條件',deadline='測試期限',caveat='測試限制',conclusion='測試結尾')
    with patch('builtins.print'):
        b=validate_bridges(FALLBACK);s=compose(fake,b)
    assert len(s)==6 and fake['benefit'] in s[1]['narration']
    for k,v in [('hook','拿到50%喔！'),('deadline_lead','明天截止喔！'),('benefit_lead','免費領取喔！'),('outro','好康喔')]:
        bad=dict(FALLBACK);bad[k]=v
        try:validate_bridges(bad)
        except StopV42:pass
        else:raise AssertionError('Unsafe bridge accepted: '+k)
    b2=dict(FALLBACK);b2['hook']='一起來了解喔！';validate_bridges(b2)
    assert all(x['publication_approved'] is False for x in [{'publication_approved':False}])
    # Renderer must be present but no network, Azure, video, or email execution here.
    assert RENDER_MOD.is_file() and REVIEW_MOD.is_file()
    print('SELFTEST PASS: 9 local checks; locked reviewed text, six scenes, safety guards, and renderer present')

def cli():
    pa=argparse.ArgumentParser(description='V4.2 Gemini-reviewed internal preview; never publishes')
    sub=pa.add_subparsers(dest='cmd',required=True)
    sub.add_parser('selftest')
    for op in ('draft','preview'):
        q=sub.add_parser(op);q.add_argument('--input',required=True)
        if op=='draft':q.add_argument('--mode',choices=('offline','gemini'),default='gemini');q.add_argument('--model',default=MODEL)
    args=pa.parse_args()
    try:
        if args.cmd=='selftest':selftest()
        elif args.cmd=='draft':draft(args.input,args.model,args.mode)
        else:render(args.input)
    except (StopV42,OSError,KeyError,ValueError,RuntimeError,subprocess.CalledProcessError) as e:
        print('V4.2 STOP:',str(e),file=sys.stderr);return 2
    return 0
if __name__=='__main__':sys.exit(cli())
